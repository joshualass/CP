void solve() {
    
    int n; cin >> n;
    vector<vector<int>> adj(n);
    for(int i = 1; i < n; i++) {
        int u, v; cin >> u >> v;
        u--; v--;
        adj[u].push_back(v);
        adj[v].push_back(u);
    }

    string x, y; cin >> x >> y;
    Z res = 0;
    int ok = 1;
    vector<int> pc(n, -1);

    auto dfs = [&](auto self, int i, int p, int d, Z mul, int t) -> void {
        int cur = x[i] - '0', targ = y[i] - '0';
        
        int th = ((cur ^ t) != targ);
        if(pc[d] == -1) {
            pc[d] = th;
            if(th) res += mul;
        } else {
            if(pc[d] != th) {
                ok = 0;
            }
        }

        for(int c : adj[i]) {
            if(c != p) {
                self(self, c, i, d + 1, mul * 2, (cur + t + th) >= 2);
            }
        }

    };

    dfs(dfs, 0, -1, 0, 1, 0);

    if(ok) {
        cout << res << '\n';
    } else {
        cout << "-1\n";
    }

}

signed main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);

    int casi; cin >> casi;
    for(int i = 0; i < casi; i++) {

        solve();
    }

    return 0;
}